            }
            return;
        }
    }

    if (add == nullptr) {
        if (ncols < 1024) {
            const dim3 block_dims(WARP_SIZE, 1, 1);
            norm_f32<WARP_SIZE, true><<<blocks_num, block_dims, 0, stream>>>(
